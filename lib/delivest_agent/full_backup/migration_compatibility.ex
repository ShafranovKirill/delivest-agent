  @baseline MapSet.new(
              for n <- 2..10, do: "202612100000" <> String.pad_leading(to_string(n), 2, "0")
            )

  def legacy_versions, do: MapSet.to_list(@legacy)

  def compatible?(source, target) do
    source = MapSet.new(source)
    target = MapSet.new(target)

    allowed_missing =
      if MapSet.subset?(@baseline, source) and MapSet.subset?(@baseline, target) and
           MapSet.subset?(@legacy, source),
         do: MapSet.put(@legacy, @historical_extra),
         else: MapSet.new()

    source
    |> MapSet.difference(target)
    |> MapSet.difference(allowed_missing)
    |> MapSet.size() == 0
  end
